# 【包的作用】
# - jieba：中文分词库，"结巴"中文分词
#   - 安装：pip install jieba
#   - 官网：https://github.com/fxsjy/jieba
#   - 特点：纯 Python 实现，无需编译，支持自定义词典和词性标注
# - typing：Python 标准库，用于类型注解（List、Dict、Optional 等）
#
# 【jieba 分词模式对比】
# ┌──────────────────────┬──────────────────────────────────┬──────────────────┐
# │ 模式                 │ API                              │ 示例              │
# ├──────────────────────┼──────────────────────────────────┼──────────────────┤
# │ 精确模式（默认）      │ jieba.lcut(text)                 │ 最适合文本分析    │
# │                      │ jieba.cut(text)                  │ 返回生成器，lcut  │
# │                      │                                  │ 直接返回 list     │
# ├──────────────────────┼──────────────────────────────────┼──────────────────┤
# │ 全模式               │ jieba.lcut(text, cut_all=True)   │ 把所有可能的词都  │
# │                      │                                  │ 切出来，速度快但  │
# │                      │                                  │ 有冗余            │
# ├──────────────────────┼──────────────────────────────────┼──────────────────┤
# │ 搜索引擎模式          │ jieba.lcut_for_search(text)      │ 在精确模式基础上  │
# │                      │                                  │ 再切长词，提高    │
# │                      │                                  │ 召回率            │
# └──────────────────────┴──────────────────────────────────┴──────────────────┘
#
# 示例对比：
#   text = "我爱北京天安门"
#   精确模式：   ['我', '爱', '北京', '天安门']
#   全模式：     ['我', '爱', '北京', '天安', '天安门']
#   搜索引擎模式：['我', '爱', '北京', '天安', '天安门']
#
# 【jieba 核心 API 速查】
# ┌────────────────────────────────────────────┬──────────────────────────────┐
# │ API                                        │ 说明                          │
# ├────────────────────────────────────────────┼──────────────────────────────┤
# │ jieba.lcut(text)                           │ 精确模式分词，返回 list        │
# │ jieba.lcut(text, cut_all=True)             │ 全模式分词，返回 list          │
# │ jieba.lcut_for_search(text)                │ 搜索引擎模式分词，返回 list    │
# │ jieba.add_word(word)                       │ 添加自定义词                   │
# │ jieba.del_word(word)                       │ 删除自定义词                   │
# │ jieba.load_userdict(file_path)             │ 加载自定义词典文件             │
# │ jieba.suggest_freq(segment, tune=True)     │ 调整词频，使某些词能被切出来    │
# │ jieba.enable_parallel(4)                   │ 开启并行分词（需先设置）        │
# │ jieba.disable_parallel()                   │ 关闭并行分词                   │
# └────────────────────────────────────────────┴──────────────────────────────┘
#
# 【为什么本项目用精确模式？】
# 精确模式是 jieba 的默认模式，试图将句子最精确地切开，适合文本分析。
# 本项目用于 BM25 关键词匹配，精确模式足够了——
# 全模式会产生冗余词（"天安"+"天安门"），反而降低匹配精度。
# ============================================================================

import jieba
from typing import List
from base import setup_logger

logger = setup_logger()


def preprocess_text(text: str) -> List[str]:
    """
    中文文本预处理：分词 + 小写化

    【参数】
    text: str — 待分词的原始文本，如 "Python是什么？"

    【返回值】
    List[str] — 分词后的 token 列表，如 ['python', '是', '什么', '？']
              异常时返回空列表 []

    【处理步骤】
    1. text.lower()：将英文统一转为小写（Python → python），保证匹配不区分大小写
    2. jieba.lcut()：精确模式分词，中文按词切开，英文/数字按空格和标点分开

    【为什么用 lcut 而不是 cut？】
    - cut() 返回生成器（generator），需要 list() 转换才能多次使用
    - lcut() 直接返回 list，更方便，内部就是 list(cut(...))

    【异常处理】
    AttributeError：当 text 不是字符串时（如传入 None），lower() 会抛此异常。
    返回空列表让调用方可以用统一的方式处理（如 for token in tokens 不报错）。
    """
    logger.info(f'开始预处理文本: {text[:30]}...')

    try:
        return jieba.lcut(text.lower())
    except AttributeError as e:
        logger.error(f"文本预处理失败，输入类型错误: {type(text).__name__}, 错误: {e}")
        return []


if __name__ == '__main__':
    text = "这是一个测试文本，我要吃白切鸡"
    tokens = preprocess_text(text)
    print(tokens)