# 【包的作用】
# mysql_qa 是 RAG 系统的第一级检索模块——FAQ 精确匹配。
# 负责从 MySQL 知识库中通过关键词匹配（BM25）快速查找已有问答对。
#
# 【模块组成】
# - db/mysql_client.py  → MySQL 连接管理、建表、CRUD、CSV 批量导入
# - redis_client.py     → Redis 缓存操作，JSON 序列化存取、问答缓存
# - preprocess.py       → 中文分词预处理（jieba）
# - bm25.py             → BM25 关键词检索，Softmax 归一化，阈值过滤
#
# 【两级检索策略】
# 第一级（本模块）：BM25 关键词匹配 → 快速、低成本、精确关键词
# 第二级（RAG模块）：Milvus 向量检索 → 语义理解、同义词、需要推理
# ============================================================================