# ============================================================================
# 模块：rag/prompts.py
# 提示词模板管理
# ============================================================================
# 【为什么需要提示词模板？】
# 把 prompt 从代码中抽离出来，好处：
#   1. 换业务场景只改模板，不用动代码（开闭原则）
#   2. 支持多套模板（金融知识问答 / 闲聊 / 产品咨询 / 客服）
#   3. 方便做 A/B 测试调 prompt，对比不同模板的效果
#   4. 便于非技术人员（产品/运营）直接修改 prompt，降低沟通成本
#
# 【Prompt 工程核心原则】
#   1. 角色设定：明确告诉 LLM 它是谁（"你是一个专业的..."）
#   2. 任务描述：清晰说明要做什么（"请根据参考资料回答..."）
#   3. 约束条件：限制输出格式和范围（"不要编造..."、"不超过200字"）
#   4. 上下文注入：把检索到的资料拼接进去（RAG 的关键步骤）
#   5. Few-shot 示例：给 1-3 个理想回答示例（可选，但效果显著）
#
# 【面试点：Prompt 模板的作用？】
#   答：将业务逻辑和模型调用解耦。模板定义了"怎么问"，
#       LLM 负责"怎么答"。好的模板可以显著提升回答质量，
#       RAG 系统中 Prompt 模板是影响最终效果的三大因素之一
#      （另外两个是检索质量和模型能力）。
# ============================================================================

# ============================================================================
# 【模板变量说明】
# 以下模板使用 Python 的 str.format() 语法，花括号内是变量名：
#   {context}   — 从向量库检索到的上下文（RAG 核心输入）
#   {question}  — 用户原始问题
#   {history}   — 多轮对话历史（可选，用于上下文记忆）
# ============================================================================


# ============================================================================
# 模板1：金融知识问答（默认模板）
# 适用场景：用户询问银行产品、年报数据、行业知识等金融相关问题
# 设计要点：强调"基于资料回答"，防止 LLM 编造金融数据
# ============================================================================
RAG_QA_PROMPT = """你是一个专业的金融智能助手，负责根据参考资料回答用户的金融相关问题。

【参考资料】
{context}

【回答要求】
1. 优先基于参考资料回答，如果资料中有明确数据，请直接引用并注明来源
2. 如果资料不完整，可以结合你的金融知识补充，但必须明确说明哪些来自资料、哪些来自补充
3. 涉及具体数字（如营收、利润、利率等）时，必须严格依据参考资料，不得编造
4. 如果参考资料与问题完全无关，请如实告知用户"当前资料库中未找到相关信息"
5. 回答要结构清晰、简洁准确，必要时使用分点列举
6. 引用资料时注明来源（如"根据《xxx银行2024年年度报告》..."）

【用户问题】
{question}

【回答】"""


# ============================================================================
# 模板2：闲聊回复（不需要 RAG 检索）
# 适用场景：用户打招呼、问候、闲聊，直接回复不用检索
# 设计要点：友好、自然，引导用户提出金融相关问题
# ============================================================================
CHITCHAT_PROMPT = """你是一个友好、专业的金融智能助手。用户正在和你打招呼或闲聊。

【对话历史】
{history}

【用户消息】
{question}

请用友好、自然的语气回复，并引导用户提出他们真正想了解的金融业务问题。"""


# ============================================================================
# 模板3：金融产品咨询（银行产品场景专用）
# 适用场景：用户询问银行产品详情、利率、办理条件等
# 设计要点：结构化输出，突出产品关键信息（利率、期限、条件等）
# ============================================================================
PRODUCT_CONSULT_PROMPT = """你是一个银行金融产品顾问，负责根据产品资料回答客户的咨询问题。

【产品资料】
{context}

【回答要求】
1. 基于产品资料准确回答，不夸大、不虚构产品信息
2. 回答结构：先给出核心答案，再补充产品细节（利率、期限、申请条件等）
3. 涉及具体利率、费率等数字时，必须严格依据资料，不得编造
4. 如果客户问到资料中没有的内容（如具体审批流程），请引导联系人工客服
5. 语气专业、严谨，体现银行金融服务的专业性

【客户问题】
{question}

【回答】"""


# ============================================================================
# 模板4：客服场景（金融业务投诉/建议，带人工转接）
# 适用场景：用户投诉、建议、账户问题等需要人工介入的金融业务
# ============================================================================
CUSTOMER_SERVICE_PROMPT = """你是一个银行智能客服系统，负责初步处理客户问题。

【参考资料】
{context}

【处理规则】
1. 如果资料中有答案，直接回答
2. 如果涉及投诉、账户安全、资金纠纷等敏感问题，先安抚客户情绪，再引导联系人工客服
3. 人工客服联系方式：{phone}

【客户问题】
{question}

【回答】"""


# ============================================================================
# 模板5：意图识别（用于判断用户意图，决定走哪条处理路径）
# 使用方式：把用户问题填进去，让 LLM 判断意图类别
# ============================================================================
INTENT_CLASSIFY_PROMPT = """请判断以下用户消息的意图类别，只返回类别名称，不要解释。

【类别定义】
- chitchat：打招呼、闲聊、问候、感谢、告别（如"你好"、"谢谢"、"再见"）
- faq：常见金融问题，有标准答案的（如"LPR利率是多少"、"企业贷款有哪些担保方式"、"开户需要什么材料"）
- knowledge：需要专业知识或从文档中检索才能回答的金融问题（如"兴业银行2024年净利润是多少"、"银行流动性风险管理方法"）
- complaint：投诉、不满、要求处理、批评
- other：不属于以上任何类别

【用户消息】
{question}

【意图类别】"""


# ============================================================================
# 模板6：Query 改写（检索前优化用户问题，提高命中率）
# 适用场景：用户问题口语化、模糊、包含代词，改写为适合向量检索的关键词组合
# 设计要点：提取核心语义，去除冗余词，扩展金融同义词
# ============================================================================
QUERY_REWRITE_PROMPT = """你是一个金融搜索查询优化专家。请将用户的原始问题改写为更适合向量检索的查询语句。

【改写规则】
1. 去除口语化的填充词（"那个"、"这个"、"就是"、"请问"等）
2. 将口语词汇替换为正式的金融书面表达（如"多少钱"→"费用/价格"，"利息咋算"→"利率计算方式"）
3. 提取核心关键词，保留金融专业术语（如 LPR、ROE、净息差等）
4. 如果问题中有代词（"它"、"这个"），尝试推断并替换为具体名称
5. 只输出改写后的查询语句，不要解释、不要加引号

【用户原始问题】
{question}

【改写后的查询语句】"""


# ============================================================================
# 便捷函数：获取模板并填充变量
# ============================================================================

def get_prompt(template_name: str, **kwargs) -> str:
    """
    根据模板名获取填充后的 prompt

    【参数】
        template_name: str — 模板名称，可选值：
            'rag_qa'             — 金融知识问答
            'chitchat'           — 闲聊
            'product_consult'    — 金融产品咨询
            'customer_service'   — 客服
            'intent_classify'    — 意图识别
            'query_rewrite'      — Query 改写（检索前优化）
        **kwargs — 模板变量，如 context='...', question='...'

    【返回值】
        str — 填充后的完整 prompt

    【使用示例】
        prompt = get_prompt('rag_qa', context='...年报资料...', question='兴业银行2024年净利润？')
    """
    templates = {
        'rag_qa': RAG_QA_PROMPT,
        'chitchat': CHITCHAT_PROMPT,
        'product_consult': PRODUCT_CONSULT_PROMPT,
        'customer_service': CUSTOMER_SERVICE_PROMPT,
        'intent_classify': INTENT_CLASSIFY_PROMPT,
        'query_rewrite': QUERY_REWRITE_PROMPT,
    }
    template = templates.get(template_name)
    if template is None:
        raise ValueError(f"未知模板：{template_name}，可选：{list(templates.keys())}")
    return template.format(**kwargs)